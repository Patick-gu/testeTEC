                                <h2 id="autenticacao-POSTapi-login">Login do Usuário</h2>

<p>
</p>

<p>Autentica um usuário usando e-mail e senha e retorna um token JWT (JSON Web Token)
que deve ser usado no header "Authorization: Bearer {token}" nas rotas privadas.</p>

