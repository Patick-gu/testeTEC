    "http://localhost:5447/api/login" \
    --header "Content-Type: application/json" \
    --header "Accept: application/json" \
    --data "{
    \"email\": \"patrick@kasterweb.com\",
    \"password\": \"secreta123\"
}"
</code></pre></div>


