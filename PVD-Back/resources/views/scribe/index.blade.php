                    <h2 id="usuarios-GETapi-users">Listar ou Buscar Usuários</h2>

<p>
</p>

<p>Retorna a lista de todos os usuários (atendentes) cadastrados no PDV.
Permite filtragem de busca (case-insensitive) através do parâmetro na URL.</p>

<span id="example-requests-GETapi-users">
<blockquote>Example request:</blockquote>


<div class="bash-example">
    <pre><code class="language-bash">curl --request GET \
    --get "http://localhost:5447/api/users?name=Pat" \
    --header "Content-Type: application/json" \
    --header "Accept: application/json"</code></pre></div>


<div class="javascript-example">
    <pre><code class="language-javascript">const url = new URL(
    "http://localhost:5447/api/users"
);

const params = {
    "name": "Pat",
};
Object.keys(params)
    .forEach(key =&gt; url.searchParams.append(key, params[key]));

const headers = {
    "Content-Type": "application/json",
    "Accept": "application/json",
